class StreamGuard {
  policy: TimingPolicy;
  signal: AbortSignal;
  connection: Connection;
  interruption: Promise<never>;
  reject!: (error: unknown) => void;
  abort: () => void;
  timer: ReturnType<typeof setTimeout> | undefined;
  interrupted: unknown;

  constructor(
    policy: TimingPolicy,
    signal: AbortSignal,
    connection: Connection
  ) {
    this.policy = policy;
    this.signal = signal;
    this.connection = connection;
    this.interruption = new Promise((_, reject) => {
      this.reject = reject;
    });
    this.abort = () =>
      this.interrupt(failure("cancelled", "stream", signal.reason));
    signal.addEventListener("abort", this.abort, { once: true });
    this.arm();
    if (signal.aborted) this.abort();
  }

  arm() {
    clearTimeout(this.timer);
    const timeout = deadlineMilliseconds(this.policy);
    if (timeout <= 0) {
      this.interrupt(failure("deadline", "stream"));
      return;
    }
    this.timer = setTimeout(
      () => this.interrupt(failure("deadline", "stream")),
      timeout
    );
  }

  interrupt(error: unknown): void {
    if (this.interrupted) return;
    this.interrupted = error;
    this.reject(error);
  }

  check(): void {
    if (this.interrupted) throw this.interrupted;
    if (this.signal.aborted) {
      this.interrupt(failure("cancelled", "stream", this.signal.reason));
      throw this.interrupted;
    }
    if (this.policy.kind === "absolute" && this.policy.at <= Date.now()) {
      this.interrupt(failure("deadline", "stream"));
      throw this.interrupted;
    }
  }

  progress(): void {
    this.check();
    if (this.policy.kind === "no-progress") this.arm();
  }

  async race<T>(operation: () => Promise<T>): Promise<T> {
    if (this.interrupted) return this.interruption;
    try {
      this.check();
    } catch {
      return this.interruption;
    }
    return Promise.race([operation(), this.interruption]);
  }

  close(): void {
    clearTimeout(this.timer);
    this.signal.removeEventListener("abort", this.abort);
  }
}

class Reader {
  connection: Connection;
  signal: AbortSignal;
  policy: TimingPolicy;
  stage: BridgeProtocolFailureStage;
  buffer: Buffer;
  guard: StreamGuard | undefined;

  constructor(
    connection: Connection,
    signal: AbortSignal,
    policy: TimingPolicy,
    stage: BridgeProtocolFailureStage
  ) {
    this.connection = connection;
    this.signal = signal;
    this.policy = anchored(policy);
    this.stage = stage;
    this.buffer = Buffer.alloc(0);
    this.guard = undefined;
  }

  async chunk(): Promise<Buffer | null> {
    try {
      const chunk = this.guard
        ? await this.guard.race(() => this.connection.read())
        : await guarded(
            () => this.connection.read(),
            this.policy,
            this.signal,
            this.stage,
            () => this.connection.destroy()
          );
      if (chunk !== null) this.guard?.progress();
      return chunk;
    } catch (error) {
      if (error instanceof BridgeProtocolFailure) throw error;
      throw failure("transport", this.stage, error);
    }
  }

  async exactly(length: number): Promise<Buffer> {
    this.guard?.check();
    const pieces = [];
    let total = 0;
    if (this.buffer.length > 0) {
      pieces.push(this.buffer.subarray(0, length));
      total = Math.min(length, this.buffer.length);
      this.buffer = this.buffer.subarray(total);
      if (total > 0) this.guard?.progress();
    }
    while (total < length) {
      const chunk = await this.chunk();
      if (chunk === null)
        throw failure("transport", this.stage, new Error("unexpected EOF"));
      const needed = length - total;
      pieces.push(chunk.subarray(0, needed));
      total += Math.min(needed, chunk.length);
      if (chunk.length > needed) this.buffer = chunk.subarray(needed);
    }
    return Buffer.concat(pieces, length);
  }

  async frame(): Promise<JsonValue> {
    const header = await this.exactly(4);
    const length = header.readUInt32BE(0);
    if (length < 2 || length > MAX_FRAME_BYTES)
      throw frameLengthFailure(this.stage);
    return strictJson(await this.exactly(length), this.stage);
  }

  async end(): Promise<void> {
    if (this.policy.kind === "absolute" && this.policy.at <= Date.now())
      throw failure("deadline", this.stage);
    if (this.buffer.length > 0) throw trailingBytesFailure(this.stage);
    const trailing = await this.chunk();
    if (trailing !== null) throw trailingBytesFailure(this.stage);
  }
}

async function openAuthenticated(options: unknown, streaming = false) {
  let payloadBytes;
  try {
    validateInput(options, streaming);
    payloadBytes = Buffer.from(JSON.stringify(options.payload));
  } catch (error) {
    throw failure("malformed", "request-write", error);
  }
  const { endpoint, credential, requestId, operation, timing, signal } =
    options;
  if (signal.aborted) throw failure("cancelled", "connect", signal.reason);
  if (timing.connect.kind === "absolute" && timing.connect.at <= Date.now()) {
    throw failure("deadline", "connect");
  }
  let connection;
  try {
    connection = connectionFor(endpoint);
  } catch (error) {
    if (error instanceof TypeError)
      throw failure("malformed", "connect", error);
    throw failure("transport", "connect", error);
  }
  try {
    try {
      await guarded(
        () => connection.connected,
        anchored(timing.connect),
        signal,
        "connect",
        () => connection.destroy()
      );
    } catch (error) {
      if (error instanceof BridgeProtocolFailure) throw error;
      throw failure("transport", "connect", error);
    }
    const challengeReader = new Reader(
      connection,
      signal,
      timing.challenge,
      "challenge"
    );
    const challengeMessage = await challengeReader.frame();
    if (challengeReader.buffer.length > 0)
      throw trailingBytesFailure("challenge");
    if (
      !exactObject(challengeMessage, ["type", "challenge"]) ||
      challengeMessage.type !== "challenge"
    ) {
      throw failure("malformed", "challenge");
    }
    const challenge = canonicalBase64(
      challengeMessage.challenge,
      32,
      "challenge"
    );
    const secret = Buffer.from(credential.secret);
    const requestTag = tag(secret, [
      "request",
      protocolVersion,
      challenge,
      credential.id,
      requestId,
      operation,
      payloadBytes,
    ]);
    const bytes = framed({
      type: "request",
      version: protocolVersion,
      credentialId: credential.id,
      requestId,
      operation,
      payload: payloadBytes.toString("base64"),
      hmac: requestTag.toString("hex"),
    });
    try {
      await guarded(
        () => connection.write(bytes),
        anchored(timing.requestWrite),
        signal,
        "request-write",
        () => connection.destroy()
      );
      connection.end();
    } catch (error) {
      if (error instanceof BridgeProtocolFailure) throw error;
      throw failure("transport", "request-write", error);
    }
    const reader = new Reader(connection, signal, timing.response, "response");
    const response = await reader.frame();
    if (
      !exactObject(response, [
        "type",
        "version",
        "requestId",
        "status",
        "payload",
        "hmac",
      ]) ||
      response.type !== "response" ||
      typeof response.version !== "number" ||
      !Number.isSafeInteger(response.version) ||
      response.version < 1 ||
      response.requestId !== requestId ||
      typeof response.status !== "string" ||
      !STATUSES.has(response.status) ||
      typeof response.payload !== "string"
    ) {
      throw failure("malformed", "response");
    }
    const responsePayload = canonicalBase64(response.payload);
    const expected = tag(secret, [
      "response",
      protocolVersion,
      response.version,
      challenge,
      credential.id,
      requestId,
      `${operation}:${response.status}`,
      responsePayload,
    ]);
    const actual = canonicalHex(response.hmac, expected.length);
    if (!timingSafeEqual(actual, expected))
      throw failure("authentication", "response");
    let parsed;
    try {
      parsed = strictJson(responsePayload);
    } catch (error) {
      throw payloadFailure(
        "response",
        error instanceof Error ? error.cause : error
      );
    }
    if (response.status === "version-mismatch") {
      if (
        !exactObject(parsed, ["clientVersion", "companionVersion"]) ||
        parsed.clientVersion !== protocolVersion ||
        parsed.companionVersion !== response.version ||
        response.version === protocolVersion
      )
        throw versionDataFailure("response");
    } else if (response.version !== protocolVersion)
      throw versionDataFailure("response");
    return {
      connection,
      reader,
      challenge,
      secret,
      status: response.status as BridgeProtocolStatus,
      payload: parsed,
    };
  } catch (error) {
    connection.destroy();
    throw error;
  }
}

class BinaryByteSource {
  reader: Reader;
  incomplete: boolean;

  constructor(reader: Reader) {
    this.reader = reader;
    this.incomplete = false;
  }

  readExactly(length: number): AsyncIterable<Uint8Array> {
    if (!Number.isSafeInteger(length) || length < 0)
      throw new TypeError("length must be a non-negative safe integer");
    if (this.incomplete) throw new TypeError("an exact read is already active");
    this.incomplete = true;
    let remaining = length;
    const source = this;
    return (async function* () {
      try {
        while (remaining > 0) {
          const chunk = await source.reader.exactly(
            Math.min(MAX_FRAME_BYTES, remaining)
          );
          remaining -= chunk.length;
          yield chunk;
        }
      } finally {
        if (remaining === 0) source.incomplete = false;
      }
    })();
  }

  verifyComplete(): void {
    if (this.incomplete) throw failure("malformed", "stream");
  }
}

class AuthenticatedFrameSource implements AsyncIterable<JsonValue> {
  reader: Reader;
  secret: Buffer;
  challenge: Buffer;
  credentialId: string;
  requestId: string;
  iterated: boolean;

  constructor(
    reader: Reader,
    secret: Buffer,
    challenge: Buffer,
    credentialId: string,
    requestId: string
  ) {
    this.reader = reader;
    this.secret = secret;
    this.challenge = challenge;
    this.credentialId = credentialId;
    this.requestId = requestId;
    this.iterated = false;
  }

  [Symbol.asyncIterator]() {
    if (this.iterated)
      throw new TypeError("authenticated frames can only be iterated once");
    this.iterated = true;
    let sequence = 0;
    return {
      next: async () => {
        const message = await this.reader.frame();
        if (
          !exactObject(message, [
            "type",
            "version",
            "requestId",
            "streamSequence",
            "payload",
            "hmac",
          ]) ||
          message.type !== "level-event" ||
          message.version !== protocolVersion ||
          message.requestId !== this.requestId ||
          message.streamSequence !== sequence ||
          typeof message.payload !== "string" ||
          typeof message.hmac !== "string"
        ) {
          throw failure("malformed", "stream");
        }
        const payload = canonicalBase64(message.payload, undefined, "stream");
        const expected = tag(this.secret, [
          "stream",
          protocolVersion,
          message.version,
          this.challenge,
          this.credentialId,
          this.requestId,
          sequence,
          payload,
        ]);
        const actual = canonicalHex(message.hmac, expected.length, "stream");
        if (!timingSafeEqual(actual, expected))
          throw failure("authentication", "stream");
        sequence += 1;
        return { done: false, value: strictJson(payload, "stream") };
      },
    };
  }
}

export async function request(
  options: BridgeProtocolRequest
): Promise<BridgeProtocolResponse> {
  const opened = await openAuthenticated(options);
  try {
    await opened.reader.end();
    return { status: opened.status, payload: opened.payload };
  } finally {
    opened.connection.destroy();
  }
}

export async function withStream<T>(
  options: BinaryStreamRequest,
  consumer: (context: BinaryStreamContext) => T | Promise<T>
): Promise<BridgeProtocolStreamResponse<T>>;
export async function withStream<T>(
  options: AuthenticatedFrameStreamRequest,
  consumer: (context: AuthenticatedFrameStreamContext) => T | Promise<T>
): Promise<BridgeProtocolStreamResponse<T>>;
export async function withStream<T>(
  options: StreamRequest,
  consumer: (context: never) => T | Promise<T>
): Promise<BridgeProtocolStreamResponse<T>> {
  if (typeof consumer !== "function")
    throw failure(
      "malformed",
      "request-write",
      new TypeError("consumer is required")
    );
  const opened = await openAuthenticated(options, true);
  const { connection, reader, challenge, secret, status, payload } = opened;
  try {
    if (status !== "ok") {
      reader.policy = anchored(options.timing.end);
      reader.stage = "stream";
      await reader.end();
      return { status, payload };
    }
    const guard = new StreamGuard(
      anchored(options.timing.stream),
      options.signal,
      connection
    );
    reader.guard = guard;
    reader.stage = "stream";
    let source;
    const context =
      options.kind === "binary"
        ? { metadata: payload, bytes: (source = new BinaryByteSource(reader)) }
        : {
            metadata: payload,
            frames: new AuthenticatedFrameSource(
              reader,
              secret,
              challenge,
              options.credential.id,
              options.requestId
            ),
          };
    let value;
    try {
      value = await guard.race(() =>
        Promise.resolve().then(() => consumer(context as never))
      );
    } finally {
      guard.close();
      reader.guard = undefined;
    }
    if (source) {
      source.verifyComplete();
      reader.policy = anchored(options.timing.end);
      await reader.end();
    }
    return { status, payload, value };
  } finally {
    connection.destroy();
  }
}
