const CANONICAL_IDENTITY =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/;

// A Bridge identity has one canonical form, and every identity is generated by `randomUUID`, so a
// non-canonical spelling can only come from a hand-written file. Do not normalise one here: the
// companion's `readCredential` rejects a non-canonical identity in its own credential store, and its
// request authentication looks that store up by exact match, so lowercasing a hand-written identity
// would only replace this rejection with an authentication failure against an identity the companion
// does not hold, and would suggest re-spelling the file instead of generating one.
export function isCanonicalIdentity(value: unknown): value is string {
  return typeof value === "string" && CANONICAL_IDENTITY.test(value);
}

export class BridgeProtocolFailure extends Error {
  readonly kind: BridgeProtocolFailureKind;
  readonly stage: BridgeProtocolFailureStage;

  constructor(
    kind: BridgeProtocolFailureKind,
    stage: BridgeProtocolFailureStage,
    cause?: unknown
  ) {
    super(
      `${kind} during ${stage}`,
      cause === undefined ? undefined : { cause }
    );
    this.name = "BridgeProtocolFailure";
    this.kind = kind;
    this.stage = stage;
  }
}

function failure(
  kind: BridgeProtocolFailureKind,
  stage: BridgeProtocolFailureStage,
  cause?: unknown
) {
  return new BridgeProtocolFailure(kind, stage, cause);
}

function protocolCause(code: string, message: string) {
  return Object.assign(new Error(message), { code });
}

