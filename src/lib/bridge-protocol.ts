function exactObject(
  value: unknown,
  keys: readonly string[]
): value is Record<string, unknown> {
  return (
    value !== null &&
    typeof value === "object" &&
    !Array.isArray(value) &&
    Object.keys(value).sort().join("\0") === [...keys].sort().join("\0")
  );
}

function validateJson(
  value: unknown,
  seen: Set<object> = new Set()
): asserts value is JsonValue {
  if (value === null || typeof value === "string" || typeof value === "boolean")
    return;
  if (typeof value === "number") {
    if (Number.isFinite(value)) return;
    throw new TypeError("JSON numbers must be finite");
  }
  if (typeof value !== "object")
    throw new TypeError("payload is not JSON-representable");
  if (seen.has(value)) throw new TypeError("payload must not be cyclic");
  seen.add(value);
  for (
    let prototype: object | null = value;
    prototype;
    prototype = Object.getPrototypeOf(prototype) as object | null
  ) {
    if (Object.getOwnPropertyDescriptor(prototype, "toJSON"))
      throw new TypeError("payload serialization hooks are unsupported");
  }
  if (Array.isArray(value)) {
    for (let index = 0; index < value.length; index += 1) {
      const descriptor = Object.getOwnPropertyDescriptor(value, String(index));
      if (!descriptor) throw new TypeError("payload arrays must not be sparse");
      if (!("value" in descriptor))
        throw new TypeError("payload accessors are unsupported");
      validateJson(descriptor.value, seen);
    }
  } else {
    const prototype: object | null = Object.getPrototypeOf(value) as
      object | null;
    if (prototype !== Object.prototype && prototype !== null)
      throw new TypeError("payload must contain only JSON objects");
    for (const key of Object.keys(value)) {
      const descriptor = Object.getOwnPropertyDescriptor(value, key);
      if (!descriptor || !("value" in descriptor))
        throw new TypeError("payload accessors are unsupported");
      validateJson(descriptor.value, seen);
    }
  }
  seen.delete(value);
}

function strictJson(
  bytes: Uint8Array,
  stage: BridgeProtocolFailureStage = "response"
): JsonValue {
  let text;
  try {
    text = new TextDecoder("utf-8", { fatal: true }).decode(bytes);
  } catch (error) {
    throw failure("malformed", stage, error);
  }
  let parsed: unknown;
  try {
    parsed = JSON.parse(text) as unknown;
    validateJson(parsed);
  } catch (error) {
    throw failure("malformed", stage, error);
  }
  let index = 0;
  const whitespace = () => {
    while (/\s/.test(text[index] ?? "")) index += 1;
  };
  const string = () => {
    const start = index++;
    while (index < text.length) {
      if (text[index] === "\\") index += 2;
      else if (text[index++] === '"')
        return JSON.parse(text.slice(start, index));
    }
    throw failure("malformed", stage);
  };
  const value = () => {
    whitespace();
    if (text[index] === "{") {
      index += 1;
      whitespace();
      const keys = new Set();
      if (text[index] === "}") {
        index += 1;
        return;
      }
      while (true) {
        if (text[index] !== '"') throw failure("malformed", stage);
        const key = string();
        if (keys.has(key)) throw failure("malformed", stage);
        keys.add(key);
        whitespace();
        if (text[index++] !== ":") throw failure("malformed", stage);
        value();
        whitespace();
        if (text[index] === "}") {
          index += 1;
          return;
        }
        if (text[index++] !== ",") throw failure("malformed", stage);
        whitespace();
      }
    }
    if (text[index] === "[") {
      index += 1;
      whitespace();
      if (text[index] === "]") {
        index += 1;
        return;
      }
      while (true) {
        value();
        whitespace();
        if (text[index] === "]") {
          index += 1;
          return;
        }
        if (text[index++] !== ",") throw failure("malformed", stage);
      }
    }
    if (text[index] === '"') {
      string();
      return;
    }
    const start = index;
    while (index < text.length && !/[\s,}\]]/.test(text[index])) index += 1;
    if (index === start) throw failure("malformed", stage);
  };
  value();
  whitespace();
  if (index !== text.length) throw failure("malformed", stage);
  return parsed;
}

function canonicalBase64(
  value: unknown,
  expectedBytes?: number,
  stage: BridgeProtocolFailureStage = "response"
) {
  if (
    typeof value !== "string" ||
    value.length === 0 ||
    value.length % 4 !== 0 ||
    !/^(?:[A-Za-z0-9+/]{4})*(?:[A-Za-z0-9+/]{2}==|[A-Za-z0-9+/]{3}=)?$/.test(
      value
    )
  ) {
    throw encodingFailure(stage);
  }
  const decoded = Buffer.from(value, "base64");
  if (
    decoded.toString("base64") !== value ||
    (expectedBytes !== undefined && decoded.length !== expectedBytes)
  ) {
    throw encodingFailure(stage);
  }
  return decoded;
}

function canonicalHex(
  value: unknown,
  expectedBytes: number,
  stage: BridgeProtocolFailureStage = "response"
) {
  if (
    typeof value !== "string" ||
    value.length !== expectedBytes * 2 ||
    !/^[0-9a-f]+$/.test(value)
  ) {
    throw failure(
      "authentication",
      stage,
      protocolCause("ERR_BRIDGE_ENCODING", "noncanonical hexadecimal")
    );
  }
  return Buffer.from(value, "hex");
}

type AuthenticationField = string | number | Uint8Array;

function authEncoding(fields: readonly AuthenticationField[]): Buffer {
  const pieces = [Buffer.from("pi-dictation-bridge-auth-v1\0")];
  for (const field of fields) {
    const value =
      field instanceof Uint8Array
        ? Buffer.from(field)
        : Buffer.from(String(field));
    const length = Buffer.allocUnsafe(4);
    length.writeUInt32BE(value.length);
    pieces.push(length, value);
  }
  return Buffer.concat(pieces);
}

function tag(
  secret: Uint8Array,
  fields: readonly AuthenticationField[]
): Buffer {
  return createHmac("sha256", secret).update(authEncoding(fields)).digest();
}

function framed(value: JsonObject): Buffer {
  const body = Buffer.from(JSON.stringify(value));
  if (body.length < 2 || body.length > MAX_FRAME_BYTES)
    throw frameLengthFailure("request-write");
  const header = Buffer.allocUnsafe(4);
  header.writeUInt32BE(body.length);
  return Buffer.concat([header, body]);
}

function validateTiming(
  timing: unknown,
  streaming = false
): asserts timing is RequestTimingPolicy | StreamTimingPolicy {
  const keys = [
    "connect",
    "challenge",
    "requestWrite",
    "response",
    ...(streaming ? ["stream", "end"] : []),
  ];
  if (!exactObject(timing, keys)) throw new TypeError("invalid timing policy");
  for (const policy of Object.values(timing)) {
    if (
      !exactObject(policy, ["kind", "at"]) &&
      !exactObject(policy, ["kind", "timeoutMs"])
    ) {
      throw new TypeError("invalid timing policy");
    }
    if (
      policy.kind === "absolute" &&
      typeof policy.at === "number" &&
      Number.isFinite(policy.at)
    )
      continue;
    if (
      (policy.kind === "no-progress" || policy.kind === "phase") &&
      typeof policy.timeoutMs === "number" &&
      Number.isFinite(policy.timeoutMs) &&
      policy.timeoutMs > 0
    )
      continue;
    throw new TypeError("invalid timing policy");
  }
}

type ValidatedInput = Omit<BridgeProtocolRequest, "endpoint"> & {
  endpoint: unknown;
};
type ValidatedStreamInput = Omit<StreamRequest, "endpoint"> & {
  endpoint: unknown;
};

function validateInput(
  options: unknown,
  streaming = false
): asserts options is ValidatedInput | ValidatedStreamInput {
  if (options === null || typeof options !== "object")
    throw new TypeError("request options are required");
  const candidate = options as Record<string, unknown>;
  if (!isCanonicalIdentity(candidate.requestId)) {
    throw new TypeError("requestId must be a canonical UUID");
  }
  if (
    typeof candidate.operation !== "string" ||
    candidate.operation.length === 0
  )
    throw new TypeError("operation is required");
  const credential = candidate.credential;
  if (credential === null || typeof credential !== "object")
    throw new TypeError("invalid credential");
  const credentialFields = credential as Record<string, unknown>;
  const credentialSecret = credentialFields.secret;
  if (
    !isCanonicalIdentity(credentialFields.id) ||
    !(credentialSecret instanceof Uint8Array) ||
    credentialSecret.byteLength !== 32
  ) {
    throw new TypeError("invalid credential");
  }
  validateTiming(candidate.timing, streaming);
  if (
    streaming &&
    candidate.kind !== "binary" &&
    candidate.kind !== "authenticated-frames"
  ) {
    throw new TypeError("invalid stream kind");
  }
  if (
    candidate.payload === null ||
    typeof candidate.payload !== "object" ||
    Array.isArray(candidate.payload)
  ) {
    throw new TypeError("payload must be a JSON object");
  }
  validateJson(candidate.payload);
  if (!(candidate.signal instanceof AbortSignal))
    throw new TypeError("signal is required");
}

function anchored(policy: TimingPolicy): TimingPolicy {
  return policy.kind === "phase"
    ? { kind: "absolute", at: Date.now() + policy.timeoutMs }
    : policy;
}

function deadlineMilliseconds(policy: TimingPolicy): number {
  return policy.kind === "absolute"
    ? Math.max(0, policy.at - Date.now())
    : policy.timeoutMs;
}

async function guarded<T>(
  operation: () => Promise<T>,
  policy: TimingPolicy,
  signal: AbortSignal,
  stage: BridgeProtocolFailureStage,
  onTimeout?: () => void
): Promise<T> {
  if (signal.aborted) throw failure("cancelled", stage, signal.reason);
  const timeout = deadlineMilliseconds(policy);
  if (timeout <= 0) throw failure("deadline", stage);
  let timer: ReturnType<typeof setTimeout> | undefined;
  let abort: (() => void) | undefined;
  const interruption = new Promise<never>((_, reject) => {
    timer = setTimeout(() => {
      reject(failure("deadline", stage));
      onTimeout?.();
    }, timeout);
    abort = () => {
      reject(failure("cancelled", stage, signal.reason));
      onTimeout?.();
    };
    signal.addEventListener("abort", abort, { once: true });
  });
  try {
    return await Promise.race([operation(), interruption]);
  } finally {
    clearTimeout(timer);
    if (abort) signal.removeEventListener("abort", abort);
  }
}

function recordTestResourceMetric(name: string, bytes: number): void {
  if (process.env.PI_DICTATION_TEST_RESOURCE_METRICS !== "1") return;
  const target = globalThis as typeof globalThis & {
    __piDictationBridgeResourceMetrics?: Record<string, number>;
  };
  const metrics = (target.__piDictationBridgeResourceMetrics ??= {});
  metrics[name] = Math.max(metrics[name] ?? 0, bytes);
}

function netConnection(endpoint: BridgeEndpoint): Connection {
  const socket =
    endpoint.type === "unix"
      ? net.createConnection({ path: endpoint.path, allowHalfOpen: true })
      : net.createConnection({
          host: endpoint.host,
          port: endpoint.port,
          allowHalfOpen: true,
        });
  const readAvailable = () => {
    if (socket.readableLength === 0) return null;
    const chunk = socket.read(Math.min(MAX_FRAME_BYTES, socket.readableLength));
    if (chunk) recordTestResourceMetric("socket", chunk.length);
    return chunk;
  };
  return {
    connected: new Promise((resolve, reject) => {
      socket.once("connect", resolve);
      socket.once("error", reject);
    }),
    read() {
      const available = readAvailable();
      if (available) return Promise.resolve(Buffer.from(available));
      if (socket.readableEnded) return Promise.resolve(null);
      return new Promise((resolve, reject) => {
        const cleanup = () => {
          socket.removeListener("readable", readable);
          socket.removeListener("end", ended);
          socket.removeListener("close", ended);
          socket.removeListener("error", failed);
        };
        const readable = () => {
          const chunk = readAvailable();
          if (chunk === null && !socket.readableEnded) {
            socket.once("readable", readable);
            return;
          }
          cleanup();
          resolve(chunk === null ? null : Buffer.from(chunk));
        };
        const ended = () => {
          cleanup();
          resolve(null);
        };
        const failed = (error: Error) => {
          cleanup();
          reject(error);
        };
        socket.once("readable", readable);
        socket.once("end", ended);
        socket.once("close", ended);
        socket.once("error", failed);
      });
    },
    write(bytes: Uint8Array) {
      return new Promise<void>((resolve, reject) =>
        socket.write(bytes, (error) => (error ? reject(error) : resolve()))
      );
    },
    end() {
      socket.end();
    },
    destroy(error?: Error) {
      socket.destroy(error);
    },
  };
}

type TestConnectionAdapter = { connect(): Connection };

function connectionFor(endpoint: unknown): Connection {
  if (endpoint !== null && typeof endpoint === "object") {
    const adapter = (endpoint as Record<PropertyKey, unknown>)[TEST_ADAPTER];
    if (
      adapter !== null &&
      typeof adapter === "object" &&
      typeof (adapter as Partial<TestConnectionAdapter>).connect === "function"
    ) {
      return (adapter as TestConnectionAdapter).connect();
    }
  }
  if (
    endpoint === null ||
    typeof endpoint !== "object" ||
    (!(
      "type" in endpoint &&
      endpoint.type === "unix" &&
      "path" in endpoint &&
      typeof endpoint.path === "string"
    ) &&
      !(
        "type" in endpoint &&
        endpoint.type === "tcp" &&
        "host" in endpoint &&
        typeof endpoint.host === "string" &&
        "port" in endpoint &&
        typeof endpoint.port === "number" &&
        Number.isInteger(endpoint.port) &&
        endpoint.port >= 1 &&
        endpoint.port <= 65_535
      ))
  ) {
    throw new TypeError("invalid endpoint");
  }
  return netConnection(endpoint as BridgeEndpoint);
}

